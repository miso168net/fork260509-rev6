    ran = "②重算冪等" + ("" if notes else "與③零手改兩道")
    return 0, notes + [f"{TAG} ✓ 產出檔集 {count} 支＝產物檔頭集＝憲法列產物檔組（雙向）；{ran}皆 byte 相等（{time.perf_counter() - t0:.1f}s）"]


