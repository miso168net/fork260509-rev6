def _write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(data)


class _FakeRepo:
    """合成 repo 根：compose 兩檔＋憲法＋base-web 工作樹（產物四支＝CANON、另一支散文提及檔頭字樣之手寫檔）＋上游基線。"""

    def __init__(self, compose=True, baseline=True, constitution=SYN_CONSTITUTION):
        self._args = (compose, baseline, constitution)

    def __enter__(self):
        compose, baseline, constitution = self._args
        self._tmp = tempfile.TemporaryDirectory()
        root = self._tmp.name
        for name in COMPOSE_FILES if compose else ():
            _write(os.path.join(root, name), b"services: {}\n")
        _write(os.path.join(root, CONSTITUTION_REL), constitution.encode())
