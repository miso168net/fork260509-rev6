def main(argv):
    args = list(argv[1:])
    constitution = os.path.join(REPO_ROOT, CONSTITUTION_REL)
    if "--constitution" in args:
        idx = args.index("--constitution")
        if idx + 1 >= len(args):
            _say(USAGE, err=True)
            return 64
        constitution = args[idx + 1]
        del args[idx:idx + 2]
    cmd = args[0] if args else "check"
