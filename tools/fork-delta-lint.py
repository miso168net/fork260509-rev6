def _code_of_line(line, closing):
    """單行去註解：回（碼文本, 新 closing 態）。`closing`＝跨行區塊註解的待閉合 token
    （None＝不在註解內）。★逐字元掃描、正確處理跨行 /* */、<!-- --> 之開閉——含『同行
    閉合後緊接碼』（rev5 對抗驗證 NF-A：`*/ code` 不再整行丟棄）與『同行連續 /* */ /* …』
    （rev5 對抗驗證 NF-C：第二註解 body 不洩為碼）；行註解 // 到行尾（不跨行、closing 不置位）。
    唯一消費者＝[`_block_code_added`]（新增型圈界掃描）——去註解規則只此一處（rev5 曾與語意守
    共用，002 刀 U0 隨三組語意守移除後只剩此面）。已知界線：不解析字串常值、字串內的 `/*` 會被當註解起首。"""
    rest, code = line, ""
    while rest:
        if closing:                          # 在跨行區塊註解內、找閉合
            k = rest.find(closing)
            if k < 0:
                return code, closing
            rest, closing = rest[k + len(closing):], None
            continue
        cands = [(rest.find(t), t) for t in ("//", "/*", "<!--") if t in rest]
        if not cands:
            return code + rest, None
        i, t = min(cands)
        code += rest[:i]
        if t == "//":
            return code, None                # 行註解到行尾
        closing, rest = ("*/" if t == "/*" else "-->"), rest[i + len(t):]
    return code, closing


def _block_code_added(added):
    """回 added 各『去註解後仍有實質碼』的行（原行原貌）。去註解規則見 [`_code_of_line`]。"""
    out, closing = [], None
    for l in added:
        code, closing = _code_of_line(l, closing)
        if code.strip():
            out.append(l)
    return out


def _structural_only(line):
    """純結構標點行（}、);、],… 無任何識別碼字元）＝區塊延續、不需獨立圈界（避免對閉合括號誤報）。"""
    return not re.search(r"[0-9A-Za-z_$]", line)


def _block_has_marker(added):
    """change-block 內有無合法 rev6 標記——限『註解行』且含 [rev6-inline（排除字串常值內同名子字串
    的自我認證：rev5 對抗驗證 FN2）。`#` 臂＝`.env*` 之註解形（rev5:B-063：ADAPT 標記為 `# [rev6-inline …]`
    裸形）、判準收窄為「去 `#` 與空白後**緊接** `[rev6-inline`」：`#` 在 .ts 是合法識別字起首
    （private field），寬形（起首 `#` 且行內任處含 token）會讓 `#tag = 'x [rev6-inline] y';`
    自我認證整個新增塊＝FN2 在 `#` 臂重開（self-test B63g 釘住）。"""
    for s in (l.strip() for l in added):
        if s.startswith(("//", "/*", "*", "<!--")) and "[rev6-inline" in s:
            return True
        if s.startswith("#") and s.lstrip("#").lstrip().startswith("[rev6-inline"):
            return True
    return False


