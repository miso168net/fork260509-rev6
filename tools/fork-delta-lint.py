        # 「軌道名不在授權名冊」——裝飾性微調不得產生誤導性紅。
        name = cells[1].strip().strip("*★ ") if len(cells) > 1 else ""
        # ★§III.2 續列守（rev5 fix 輪補）：首欄留空（markdown「省略重複欄值」的常見整理手法——
        # 同軌道名連續重複多列、正是會被順手美化的形）若走下方 skip＝靜默漏收整個用途；後果與
