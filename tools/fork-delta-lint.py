def assert_baseline():
    """掃描面可達性斷言之一（rev6 取代 rev5「修改型 ≥1 處」的列數斷言）：源倉在場且切在 example。
    源倉缺席＝die rc 2（bootstrap 已斷言在場、正常不觸；唯讀捷徑模式 `git submodule update --init`
    無源倉＝無基線、CLAUDE.md §3 明寫不可做 base-web 開發）。"""
    if not os.path.isdir(FORK):
        die(f"最原始源-基線目錄不存在：{FORK}（bootstrap 建源倉後自動恢復實跑；bash tools/bootstrap.sh）")
    r = sh(["git", "rev-parse", "--abbrev-ref", "HEAD"], FORK)
    if r.returncode != 0:
        die(f"基線 repo 不可讀：{FORK}")
    cur = r.stdout.strip()
    if cur != BASELINE:
        die(f"最原始源-基線未就位：{FORK} 現在 '{cur}'、須切到 '{BASELINE}'"
            f"（git -C {FORK} checkout {BASELINE}）")


def _in_scan_scope(f):
    """rev5:B-063 收案規則：src/ 之 .ts/.vue＋build/ 之 .ts＋**根層** `.env` 族。
    `.env*` 無副檔名、獨立收案（根層限定、以 .env 起首），不硬塞 endswith 濾網。"""
    if f.startswith("src/"):
        return f.endswith((".ts", ".vue"))
    if f.startswith("build/"):
        return f.endswith(".ts")
    return "/" not in f and f.startswith(".env")


def changed_files(repo=BASEWEB, baseline=BASELINE):
    """掃描面（rev5:B-063 擴）：rev4 舊面只 `-- src/` ⇒ `.env*` 與 `build/` 的 fork-delta 全靠人工
    review、upstream rebase 解錯不會紅。repo/baseline 參數化＝讓 self-test 能以暫存 git
    fixture 走**同一條**真掃描鏈（pathspec＋濾網零打樁），變異「縮回 src/」即測紅。
    ★git diff 非零即 die＝掃描面可達性斷言之二（零差異與「diff 跑不動」是兩件事、絕不同回空集）。"""
    r = sh(["git", "diff", "--name-only", baseline, "--", "src/", "build/", ".env*"], repo)
    if r.returncode != 0:
        die(f"無法 diff base-web vs {baseline}：{r.stderr.strip()}")
    return [f for f in r.stdout.splitlines() if _in_scan_scope(f)]


def scan(s1, s2, repo=BASEWEB, baseline=BASELINE):
    """回 (errs, unmarked, rogue, checked_total, stats)；stats＝{"files": 掃描面檔數,
    "new_files": 我方新檔數, "new_checked": 過新檔兩道判定之檔數}（供修改型 0 處時印出掃描面實況、
    證 vacuous 是合法的而非掃描面壞掉）。repo/baseline 參數化（同 [`changed_files`] 之 B63f 範式）
    ＝讓 self-test 以暫存 git fixture 走**同一條**真掃描鏈驗新檔兩腿的**接線**——腿寫好卻沒接上
    （rev5 形之整檔 continue）正是 002 刀 U0 fix 輪所修的病，內容級斷言看不見。"""
    errs, unmarked, rogue = [], [], []
    checked_total, new_files, new_checked = 0, 0, 0
    rels = list(changed_files(repo, baseline))
    # ── 基線原文並行預取（rev5:B-130／rev5:ADR 0061）────────────────────────────────────
    # 本函式的成本 **99% 在 subprocess 等待**、不在判定邏輯（rev5 2026-08-25 cProfile：
    # select.poll 14.338s／14.260s 總時，檔案 I/O 僅 0.167s）——每個 changed file 各起一次
    # `git show` 取基線原文，逐次序列等待。drvfs（9p）下單次約 0.29s，數十檔即十數秒。
    # ★預取只把「等待」重疊，判定邏輯與逐檔順序一字不動（下方迴圈照原序消費），
    #   故結果逐位元組相同——git show 為唯讀、對同一 BASELINE 冪等，並行無序副作用。
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as ex:
        bases = dict(zip(rels, ex.map(
            lambda r: sh(["git", "show", f"{baseline}:{r}"], repo), rels)))
    for rel in rels:
        base = bases[rel]
        ours_path = os.path.join(repo, rel)
        if base.returncode != 0:
            # ★我方新檔（基線沒有此檔）：rev5 形整檔豁免＝圈界腿與授權判定對新檔全 vacuous
            #   （002 刀 U0 fix 輪補；該刀 fork-delta 面恰為兩支新檔）。改走新檔兩道——
            #   ①檔頭圈界標記 ②標記自稱 §III.1 軌道時檔路徑須落其範圍欄新增面。
            new_files += 1
            try:
                ours = open(ours_path, encoding="utf-8").read()
            except FileNotFoundError:
                continue                     # diff 列出但工作樹已無（刪除態）——無可判定面
            if is_generated(ours):
                continue                     # 生成檔（憲法 §III 生成檔紀律）→ 重算保證、豁免手標
            marker = find_new_file_marker(ours)
            if marker is None:
                unmarked.append((rel, _first_substantive(ours) or "（檔內無實質碼行）"))
                continue
            new_checked += 1
            why = new_file_track_issue(rel, marker, s1)
            if why:
                rogue.append((rel, marker, why))
            continue
        try:
            ours = open(ours_path, encoding="utf-8").read()
        except FileNotFoundError:
            continue
        if is_generated(ours):
            continue  # 生成檔（elegant-router 等）→ fork-delta 由重算保證、豁免手標
        for m in find_missing(base.stdout, ours):
            errs.append((rel, m))
        for a in find_unmarked_additions(base.stdout, ours):
            unmarked.append((rel, a))
        hits, checked = find_rogue_tracks(rel, ours, s1, s2)
        checked_total += checked
        for line, why in hits:
            rogue.append((rel, line, why))
    return errs, unmarked, rogue, checked_total, {"files": len(rels), "new_files": new_files,
                                                  "new_checked": new_checked}


